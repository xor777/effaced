/** a drum bar from a one-char-per-row string; each char's volume (and optionally its kit note) from the maps */
function drumBar(tr: Tr, from: number, pattern: string, v: Record<string, number>, note: string = DRUM_NOTE, notes: Record<string, string> = {}): void {
  [...pattern].forEach((ch, i) => ch !== '.' && tr.n(from + i, notes[ch] ?? note, v[ch]));
}
/** rescale the volumes of the note rows in [from, to) linearly from v0 to v1 (the rhythm stays) */
function swell(tr: Tr, from: number, to: number, v0: number, v1: number): void {
  for (let k = from; k < to; k++) if (tr.cells[k].note && tr.cells[k].note !== '==') tr.v(k, Math.round(v0 + ((v1 - v0) * (k - from)) / Math.max(1, to - from - 1)));
}
/**
 * The mirror (ch16): a bell note at `row` glints back `after` rows later at `scale` × its volume, panned
 * left/right alternately, and is keyed off `life` rows after it starts (a glimpse, not a second line).
 */
let glints = 0;
function glint(row: number, after = 6, life = 8, scale = 0.38): void {
  const c = t.bell.cells[row];
  if (!c.note || c.note === '==') throw new Error(`glint: no bell note at row ${row}`);
  t.mirror.n(row + after, c.note, Math.max(1, Math.round((c.vol ?? 36) * scale)), glints++ % 2 ? '8B8' : '848');
  t.mirror.off(row + after + life);
}

